// addonMarker makes ddev treat the binaries as add-on managed files, so
// `ddev add-on get` overwrites them on update (ddev only replaces files that
// contain this signature).
const addonMarker = "#ddev-generated by the ddev-bridge add-on"

// BinDir is where the sandbox client and its symlinks live in a project.
var BinDir = filepath.Join(registry.Dir, "bin")

// gitignoreLines keep the per-developer install out of the repository: the
// client and token, the add-on's .ddev config (its post-start hook calls the
// global `ddev bridge` command, which teammates without the add-on lack) and
// the add-on metadata ddev writes on install.
var gitignoreLines = []string{
	"/" + registry.Dir + "/",
	"/.ddev/config.ddev-bridge.yaml",
	"/.ddev/addon-metadata/ddev-bridge/",
}

// gitignoreHeader introduces the block ensureGitignore appends.
const gitignoreHeader = "# ddev-bridge (per-developer install, not for the repository)"

// defaultClient is the client next to this host binary in the add-on layout:
// <dist>/host/<os>-<arch>/ddev-bridge -> <dist>/client/linux-<arch>/ddev-bridge-client.
// Sandboxes run Linux on the host's CPU architecture.
func defaultClient() string {
	exe, err := os.Executable()
	if err != nil {
		return ""
	}
	if r, err := filepath.EvalSymlinks(exe); err == nil {
		exe = r
	}
	return filepath.Join(filepath.Dir(exe), "..", "..", "client", "linux-"+runtime.GOARCH, "ddev-bridge-client")
}

// installProject puts the client into <root>/.ddev-bridge/bin, updates .gitignore,
// registers the project and approves its .ddev/.
func installProject(args []string) {
	fs := flag.NewFlagSet("install-project", flag.ExitOnError)
	client := fs.String("client", defaultClient(), "sandbox client binary to install")
	noSbx := fs.Bool("no-sbx", false, "do not add the sbx network rule")
	pos := mustParse(fs, args, 1, "[flags] [dir]")
	dir := "."
	if len(pos) > 0 {
		dir = pos[0]
	}
	root, _, err := registry.ValidateRoot(dir)
	if err != nil {
		fatal(err)
	}

	bin := filepath.Join(root, BinDir)
	if err := os.MkdirAll(bin, 0o755); err != nil {
		fatal(err)
	}
	dst := filepath.Join(bin, "ddev-bridge-client")
	if err := copyAtomic(*client, dst); err != nil {
		fatal(fmt.Errorf("install client: %w", err))
	}
	for _, name := range []string{"ddev", "drush"} {
		link := filepath.Join(bin, name)
		os.Remove(link)
		if err := os.Symlink("ddev-bridge-client", link); err != nil {
			fatal(err)
		}
	}
	fmt.Printf("installed sandbox client in %s (ddev, drush)\n", bin)

	if added, err := ensureGitignore(filepath.Join(root, ".gitignore")); err != nil {
		fatal(err)
	} else if added {
		fmt.Println("added the ddev-bridge files (client, token, add-on config) to .gitignore")
	}

	reg, err := registry.Load()
	if err != nil {
		fatal(err)
	}
	p, err := reg.Register(root)
	if err != nil {
		fatal(err)
	}
	fmt.Printf("registered %q; token in %s, .ddev/ approved\n", p.Name, registry.TokenFile)

	if *noSbx {
		return
	}
	if sbx, err := exec.LookPath("sbx"); err == nil {
		out, err := exec.Command(sbx, "policy", "allow", "network", "localhost:7474").CombinedOutput()
		if err != nil {
			fmt.Printf("could not add the sbx network rule (%v): %s\nrun: sbx policy allow network localhost:7474\n", err, strings.TrimSpace(string(out)))
		} else {
			fmt.Println("sbx: sandboxes may reach the bridge on localhost:7474")
		}
	} else {
		fmt.Println("sbx not found; on the machine that runs the sandboxes, run once: sbx policy allow network localhost:7474")
	}
}

// uninstallProject reverses installProject, including the .gitignore block.
func uninstallProject(args []string) {
	dir := "."
	if len(args) > 0 {
		dir = args[0]
	}
	root, err := filepath.Abs(dir)
	if err != nil {
		fatal(err)
	}
	reg, err := registry.Load()
	if err != nil {
		fatal(err)
	}
	if err := reg.Unregister(root); err != nil {
		fmt.Println(err)
	}
	for _, n := range []string{"ddev", "drush", "ddev-bridge-client"} {
		os.Remove(filepath.Join(root, BinDir, n))
	}
	os.Remove(filepath.Join(root, BinDir))
	os.Remove(filepath.Join(root, registry.TokenFile))
	os.Remove(filepath.Join(root, registry.Dir)) // only if empty
	fmt.Println("removed the sandbox client and token, unregistered the project")
	if removed, err := removeGitignore(filepath.Join(root, ".gitignore")); err != nil {
		fmt.Printf("could not clean .gitignore (%v); remove the ddev-bridge lines by hand\n", err)
	} else if removed {
		fmt.Println("removed the ddev-bridge lines from .gitignore")
	}
}

// removeGitignore deletes the lines ensureGitignore adds (the header and the
// entries, exactly as written) and keeps everything else. The file is kept even
// if it ends up empty, because it may be tracked.
func removeGitignore(path string) (bool, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	} else if err != nil {
		return false, err
	}
	ours := map[string]bool{gitignoreHeader: true}
	for _, l := range gitignoreLines {
		ours[l] = true
	}
	trailing := strings.HasSuffix(string(data), "\n")
	lines := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	var keep []string
	for _, l := range lines {
		if !ours[strings.TrimSpace(l)] {
			keep = append(keep, l)
		}
	}
	if len(keep) == len(lines) {
		return false, nil
	}
	out := strings.Join(keep, "\n")
	if trailing && out != "" {
		out += "\n"
	}
	return true, os.WriteFile(path, []byte(out), 0o644)
}

// copyAtomic copies src to dst via a temp file and rename, so a client that is
// running in a sandbox is never overwritten in place.
func copyAtomic(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	tmp, err := os.CreateTemp(filepath.Dir(dst), ".ddev-bridge-client-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := io.Copy(tmp, in); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o755); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), dst)
}

// ensureGitignore appends the bridge entries that are missing.
func ensureGitignore(path string) (bool, error) {
	have := map[string]bool{}
	if f, err := os.Open(path); err == nil {
		sc := bufio.NewScanner(f)
		for sc.Scan() {
			have[strings.TrimSpace(sc.Text())] = true
		}
		f.Close()
	}
	var missing []string
	for _, l := range gitignoreLines {
		if !have[l] && !have[strings.TrimPrefix(l, "/")] {
			missing = append(missing, l)
		}
	}
	if len(missing) == 0 {
		return false, nil
	}
	data, _ := os.ReadFile(path)
	prefix := ""
	if len(data) > 0 && data[len(data)-1] != '\n' {
		prefix = "\n"
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return false, err
	}
	defer f.Close()
	_, err = fmt.Fprintf(f, "%s%s\n%s\n", prefix, gitignoreHeader, strings.Join(missing, "\n"))
	return true, err
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "ddev-bridge:", err)
	os.Exit(1)
}
