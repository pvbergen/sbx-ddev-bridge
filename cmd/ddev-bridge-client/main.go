// Command ddev-bridge-client runs inside the sandbox. Install it (or symlink
// it) as `ddev` and `drush`; it forwards the command to the host bridge and
// streams the output back.
//
//	ddev drush cr         -> argv ["drush","cr"]
//	drush cr              -> argv ["drush","cr"]
//	ddev logs -s web      -> argv ["logs","-s","web"]
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"

	"ddev-bridge/internal/proto"
	"ddev-bridge/internal/registry"
)

const defaultURL = "http://host.docker.internal:7474"

// addonMarker lets `ddev add-on get` overwrite this binary on update
// (ddev only replaces files that contain this signature).
const addonMarker = "#ddev-generated by the ddev-bridge add-on"

func fail(format string, a ...any) {
	fmt.Fprintf(os.Stderr, "ddev-bridge: "+format+"\n", a...)
	os.Exit(proto.ExitBridgeError)
}

func findToken() (string, error) {
	if t := strings.TrimSpace(os.Getenv("DDEV_BRIDGE_TOKEN")); t != "" {
		return t, nil
	}
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		data, err := os.ReadFile(filepath.Join(dir, registry.TokenFile))
		if err == nil {
			return strings.TrimSpace(string(data)), nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no %s found in this directory or any parent; run `ddev-bridge register` on the host", registry.TokenFile)
		}
		dir = parent
	}
}

func main() {
	argv := os.Args[1:]
	if filepath.Base(os.Args[0]) == "drush" {
		argv = append([]string{"drush"}, argv...)
	}
	if len(argv) == 0 {
		fail("usage: ddev <command> ... or drush <command> ... (forwarded to the host bridge; denied commands exit 126 with the reason)")
	}
	if argv[0] == "--addon-marker" {
		fmt.Println(addonMarker)
		return
	}

	// In clone mode the sandbox edits its own copy; host ddev would not see the changes.
	if _, err := os.Stat("/run/sandbox/source"); err == nil && os.Getenv("DDEV_BRIDGE_ALLOW_CLONE") == "" {
		fail("this sandbox runs in clone mode; host ddev would not see your changes. Use a direct-mode sandbox.")
	}

	token, err := findToken()
	if err != nil {
		fail("%v", err)
	}
	base := os.Getenv("DDEV_BRIDGE_URL")
	if base == "" {
		base = defaultURL
	}

	// Ctrl-C / SIGTERM closes the connection; the bridge then kills the remote process group.
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	body, _ := json.Marshal(proto.RunRequest{Argv: argv})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, strings.TrimRight(base, "/")+proto.RunPath, bytes.NewReader(body))
	if err != nil {
		fail("%v", err)
	}
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Content-Type", "application/json")

	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		if ctx.Err() != nil {
			os.Exit(130)
		}
		fail("cannot reach bridge at %s: %v\n(is `ddev-bridge serve` running on the host, and is localhost:7474 allowed in the sandbox network policy?)", base, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		msg, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
		fail("bridge returned %s: %s", resp.Status, strings.TrimSpace(string(msg)))
	}

	dec := json.NewDecoder(resp.Body)
	for {
		var f proto.Frame
		if err := dec.Decode(&f); err != nil {
			if ctx.Err() != nil {
				fmt.Fprintln(os.Stderr, "\nddev-bridge: cancelled")
				os.Exit(130)
			}
			if errors.Is(err, io.EOF) {
				fail("connection closed before the command finished")
			}
			fail("invalid response from bridge: %v", err)
		}
		switch {
		case f.Exit != nil:
			if f.Denied != "" {
				fmt.Fprintf(os.Stderr, "ddev-bridge: denied: %s\n", f.Denied)
			}
			os.Exit(*f.Exit)
		case f.Stream == proto.Stderr:
			os.Stderr.Write(f.Data)
		default:
			os.Stdout.Write(f.Data)
		}
	}
}
